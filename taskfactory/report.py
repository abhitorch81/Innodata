"""Aggregate every packaged task into REPORT.md + report.html (self-contained dashboard)."""
from __future__ import annotations
import html
import json
from pathlib import Path

from .factory import TASKS
from .core import ROOT

STAGE_LABEL = {"S1_base_fails": "S1 tests fail on base", "S2_reference_passes": "S2 reference passes",
               "S3_regression_intact": "S3 existing suite intact", "S4_rule_ablations": "S4 every rule detected",
               "S5_mutation_kill": "S5 mutation kill", "S6_regression_guard": "S6 neighbour guard",
               "S7_determinism": "S7 deterministic"}


def load():
    rows = []
    for tj in sorted(TASKS.glob("*/*/task.json")):
        d = tj.parent
        t = json.loads(tj.read_text()); ev = json.loads((d / "validation.json").read_text())
        demo = json.loads((d / "demo_eval.json").read_text()) if (d / "demo_eval.json").exists() else None
        rows.append((d, t, ev, demo))
    mats = {}
    for m in sorted(TASKS.glob("*/_variation_*.json")):
        mats[f"{m.parent.name}/{m.stem[len('_variation_'):]}"] = json.loads(m.read_text())
    return rows, mats


def badge(st):
    if st.get("applicable") is False:
        return '<span class="b na">n/a</span>'
    return f'<span class="b {"ok" if st["ok"] else "bad"}">{"pass" if st["ok"] else "fail"}</span>'


def render():
    rows, mats = load()
    n = len(rows); valid = sum(r[2]["valid"] for r in rows)
    mk = [r[2]["stages"]["S5_mutation_kill"]["score"] for r in rows]
    fams = sorted({(r[1]["repo"]["name"], r[1]["family"]) for r in rows})
    ablt = sum(len(r[2]["stages"]["S4_rule_ablations"]["per_rule"]) for r in rows)
    bases = {r[1]["repo"]["name"]: r[1]["repo"]["base_commit"] for r in rows}
    css = """:root{--bg:#fff;--fg:#1b1f24;--mut:#6a737d;--ok:#1a7f37;--bad:#cf222e;--warn:#9a6700;--line:#d8dee4;--card:#f6f8fa}
@media(prefers-color-scheme:dark){:root{--bg:#0d1117;--fg:#e6edf3;--mut:#8b949e;--ok:#3fb950;--bad:#f85149;--warn:#d29922;--line:#30363d;--card:#161b22}}
body{background:var(--bg);color:var(--fg);font:15px/1.5 -apple-system,Segoe UI,Helvetica,sans-serif;margin:0;padding:24px 16px}
main{max-width:1100px;margin:auto}h1{margin:0 0 4px}h2{margin-top:34px;border-bottom:1px solid var(--line);padding-bottom:6px}
.sub{color:var(--mut)}.cards{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px;margin:18px 0}
.card{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:12px 14px}.card b{font-size:26px;display:block}
table{border-collapse:collapse;width:100%;font-size:13px}th,td{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}
.b{padding:1px 8px;border-radius:10px;font-size:12px;font-weight:600}.ok{background:color-mix(in srgb,var(--ok) 18%,transparent);color:var(--ok)}
.bad{background:color-mix(in srgb,var(--bad) 18%,transparent);color:var(--bad)}.na{background:var(--card);color:var(--mut)}
.warn{color:var(--warn)}code,.mono{font-family:ui-monospace,Menlo,monospace;font-size:12px}.hm td{text-align:center;font-family:ui-monospace,monospace}
.rules span{display:inline-block;background:var(--card);border:1px solid var(--line);border-radius:6px;padding:0 6px;margin:1px 2px;font-size:12px}
.scroll{overflow-x:auto}details{margin:6px 0}"""
    h = [f"<!doctype html><html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
         f"<title>Task Factory Report</title><style>{css}</style></head><body><main>",
         "<h1>Coding Task Factory — validation report</h1>",
         "<div class=sub>One reusable strategy: <b>rule-algebra task synthesis</b> with ablation-, mutation- and cross-task validation. "
         "Generated by <code>python -m taskfactory</code>.</div>",
         "<div class=cards>"
         f"<div class=card><b>{n}</b>tasks packaged</div><div class=card><b>{valid}/{n}</b>pass all gates</div>"
         f"<div class=card><b>{len(fams)}</b>feature families, {len(bases)} repos</div>"
         f"<div class=card><b>{ablt}</b>rule ablations, all detected</div>"
         f"<div class=card><b>{sum(mk)/max(1,len(mk)):.0%}</b>mean mutation kill</div>"
         f"<div class=card><b>{sum(r[1]['fail_to_pass_count'] for r in rows)}</b>feature tests</div></div>"]
    h.append("<div class=sub>Pinned base commits: " + ", ".join(f"<code>{k}@{v[:10]}</code>" for k, v in bases.items()) + "</div>")
    h.append("<h2>Tasks and validation evidence</h2><div class=scroll><table><tr><th>Task</th><th>Rules (requirements)</th><th>Diff</th><th>F2P / P2P</th>"
             + "".join(f"<th>{STAGE_LABEL[s].split(' ',1)[0]}</th>" for s in STAGE_LABEL) + "<th>Mutants killed</th><th>Gate</th></tr>")
    for d, t, ev, demo in rows:
        st = ev["stages"]; m = st["S5_mutation_kill"]; g = st["S6_regression_guard"]
        h.append(f"<tr><td><b>{html.escape(t['task_id'])}</b><br><span class=sub>{t['difficulty']}</span></td>"
                 f"<td class=rules>{''.join(f'<span>{html.escape(r['id'])}</span>' for r in t['rules'])}</td>"
                 f"<td>{ev['ref_patch_lines']} lines<br>{len(ev['files_touched'])} files</td>"
                 f"<td>{t['fail_to_pass_count']} / {t['pass_to_pass_count']}</td>"
                 + "".join(f"<td>{badge(st[s])}</td>" for s in STAGE_LABEL)
                 + f"<td>{m['killed']}/{m['killed'] + m['survived']} ({m['score']:.0%})</td>"
                 f"<td>{'<span class=\"b ok\">VALID</span>' if ev['valid'] else '<span class=\"b bad\">INVALID</span>'}</td></tr>")
    h.append("</table></div><div class=sub>S1–S4 and S7 gate validity. S5/S6 are reported scores (survivors are listed in validation.json; some are equivalent mutants).</div>")
    h.append("<h2>Rule ablation matrix</h2><div class=sub>For each rule, an implementation that is correct <i>except</i> for that rule is built. "
             "It must fail tests attributed to that rule. ✓ = detected (number of failing rule tests; collateral = failures attributed to other rules).</div>"
             "<div class=scroll><table><tr><th>Task</th><th>Rule dropped</th><th>Detected</th><th>#failing tests</th><th>collateral</th></tr>")
    for d, t, ev, demo in rows:
        for rid, a in ev["stages"]["S4_rule_ablations"]["per_rule"].items():
            h.append(f"<tr><td>{t['task_id']}</td><td class=mono>{rid}</td><td>{'✓' if a['caught'] else '✗'}</td><td>{a['caught_by']}</td><td>{a['collateral']}</td></tr>")
    h.append("</table></div>")
    if mats:
        h.append("<h2>Meaningful variation: cross-task matrix</h2><div class=sub>Cell (row i, column j) = share of task <i>i</i>'s feature tests "
                 "that task <i>j</i>'s <b>reference solution</b> passes. Diagonal = 1.00 by construction; every off-diagonal value &lt; 1.00 "
                 "proves the two tasks demand different observable behaviour (not just different wording).</div>")
        for k, m in mats.items():
            ids = m["variants"]
            h.append(f"<h3>{k}</h3><div class=scroll><table class=hm><tr><th>tests ↓ / reference →</th>" + "".join(f"<th>{i}</th>" for i in ids) + "</tr>")
            for i, row in enumerate(m["tests_i_vs_reference_j"]):
                h.append(f"<tr><th>{ids[i]}</th>" + "".join(
                    f"<td style='background:rgba(26,127,55,{0.15 + 0.6 * x:.2f})'>{x:.2f}</td>" if i == j else
                    f"<td style='background:rgba(207,34,46,{0.12 + 0.5 * (1 - x):.2f})'>{x:.2f}</td>" for j, x in enumerate(row)) + "</tr>")
            h.append("</table></div>")
    demos = [(t, demo) for d, t, ev, demo in rows if demo]
    if demos:
        h.append("<h2>Using a package to evaluate a coding system</h2><div class=sub>Simulated candidate solutions graded by <code>taskfactory evaluate</code>.</div>")
        for t, demo in demos:
            h.append(f"<h3>{t['task_id']}</h3><table><tr><th>Candidate</th><th>Verdict</th><th>F2P</th><th>P2P</th><th>Per requirement</th></tr>")
            for name, r in demo.items():
                h.append(f"<tr><td>{html.escape(name)}</td><td><span class='b {'ok' if r['verdict']=='RESOLVED' else 'bad'}'>{r['verdict']}</span></td>"
                         f"<td>{r.get('fail_to_pass','-')}</td><td>{r.get('pass_to_pass','-')}</td><td class=mono>{html.escape(json.dumps(r.get('per_rule', r.get('reason',''))))}</td></tr>")
            h.append("</table>")
    lim = (ROOT / "LIMITATIONS.md")
    if lim.exists():
        h.append("<h2>Honest limitations</h2><ul>" + "".join(f"<li>{html.escape(l[2:])}</li>" for l in lim.read_text().splitlines() if l.startswith("- ")) + "</ul>")
    h.append("</main></body></html>")
    (ROOT / "report.html").write_text("\n".join(h))
    # markdown summary
    md = ["# Validation summary", "", f"{valid}/{n} tasks pass all gates; mean mutation kill {sum(mk)/max(1,len(mk)):.0%}.", "",
          "| task | rules | F2P | P2P | S5 kill | gate |", "|---|---|---|---|---|---|"]
    for d, t, ev, demo in rows:
        m = ev["stages"]["S5_mutation_kill"]
        md.append(f"| {t['task_id']} | {', '.join(r['id'] for r in t['rules'])} | {t['fail_to_pass_count']} | {t['pass_to_pass_count']} | {m['score']:.0%} | {'VALID' if ev['valid'] else 'INVALID'} |")
    (ROOT / "REPORT.md").write_text("\n".join(md) + "\n")
    return n, valid
